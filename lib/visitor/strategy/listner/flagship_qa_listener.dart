/// Example class showing how Flagship can listen to QA events
class FlagshipQAListener {
  /// Start listening to QA events
  void startListening() {
    print('🎯 Flagship : Starting to listen to QAssistant messages');
  }

  /// Stop listening to events
  void stopListening() {
    print('🛑 Flagship: Stopping QA event listening...');
  }
}
